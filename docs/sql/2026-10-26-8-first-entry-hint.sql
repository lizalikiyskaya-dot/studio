-- «Первая заявка»: журнал или конкурс. Издательство остаётся своим значком.
-- Меняется только подсказка. Уже выданные значки не снимаются.

UPDATE "Badge"
SET
  hint = 'Отправьте первую заявку в журнал или на конкурс.',
  "hintFormal" = 'Отправьте первую заявку в журнал или на конкурс.'
WHERE id = 'first-entry'
  AND (
    hint IS DISTINCT FROM 'Отправьте первую заявку в журнал или на конкурс.'
    OR "hintFormal" IS DISTINCT FROM 'Отправьте первую заявку в журнал или на конкурс.'
  );
