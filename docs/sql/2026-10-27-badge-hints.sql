UPDATE "Badge" AS b
SET "sortOrder" = v.ord
FROM (
  VALUES
    ('level-5', 20),
    ('level-25', 21),
    ('level-70', 22),
    ('level-100', 23),
    ('level-150', 24),
    ('spark', 30),
    ('candle', 31),
    ('lighthouse', 32),
    ('back-in-line', 33)
) AS v(id, ord)
WHERE b.id = v.id
  AND b."sortOrder" IS DISTINCT FROM v.ord;

