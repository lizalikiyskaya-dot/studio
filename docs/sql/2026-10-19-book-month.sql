-- Рекомендуемый месяц книги. Столбец пустой, методички его не показывают.
-- Повторный запуск безопасен.
--
-- Следом — одноразовый перенос. Если название книги кончается скобками и внутри
-- только месяц (январь … декабрь, можно с годом) и/или «по желанию», эти слова
-- уходят из названия: месяц — в новый столбец, «по желанию» ставит optional.
-- Пример: «Аура, Карлос Фуэнтес (ноябрь 2026, по желанию)» становится
-- «Аура, Карлос Фуэнтес», month = «ноябрь 2026», optional = true.
-- Другие скобки («роман», заметка) остаются в названии. Уже записанный месяц
-- не затирается. Второй проход не находит таких скобок и ничего не меняет.

ALTER TABLE "Material" ADD COLUMN IF NOT EXISTS "month" TEXT;

UPDATE "Material"
SET
  title = btrim(regexp_replace(title, '[[:space:]]*\([^)]*\)[[:space:]]*$', '')),
  month = NULLIF(
    btrim(
      regexp_replace(
        btrim(substring(title FROM '\(([^)]+)\)[[:space:]]*$')),
        '(^|[[:space:]]*,[[:space:]]*)по[[:space:]]+желанию([[:space:]]*,[[:space:]]*|$)',
        '',
        'gi'
      ),
      ' ,'
    ),
    ''
  ),
  optional = optional OR (
    lower(btrim(substring(title FROM '\(([^)]+)\)[[:space:]]*$'))) ~ 'по[[:space:]]+желанию'
  )
WHERE category = 'BOOK'
  AND (month IS NULL OR btrim(month) = '')
  AND btrim(regexp_replace(title, '[[:space:]]*\([^)]*\)[[:space:]]*$', '')) <> ''
  AND lower(btrim(substring(title FROM '\(([^)]+)\)[[:space:]]*$'))) ~ '^(?:(?:(?:январ[а-яё]*|феврал[а-яё]*|март[а-яё]*|апрел[а-яё]*|ма[йя][а-яё]*|июн[а-яё]*|июл[а-яё]*|август[а-яё]*|сентябр[а-яё]*|октябр[а-яё]*|ноябр[а-яё]*|декабр[а-яё]*)(?:[[:space:]]+[12][0-9]{3})?|[12][0-9]{3})(?:[[:space:]]*,[[:space:]]*(?:(?:январ[а-яё]*|феврал[а-яё]*|март[а-яё]*|апрел[а-яё]*|ма[йя][а-яё]*|июн[а-яё]*|июл[а-яё]*|август[а-яё]*|сентябр[а-яё]*|октябр[а-яё]*|ноябр[а-яё]*|декабр[а-яё]*)(?:[[:space:]]+[12][0-9]{3})?|[12][0-9]{3}))*(?:[[:space:]]*,[[:space:]]*по[[:space:]]+желанию)?|по[[:space:]]+желанию(?:[[:space:]]*,[[:space:]]*(?:(?:январ[а-яё]*|феврал[а-яё]*|март[а-яё]*|апрел[а-яё]*|ма[йя][а-яё]*|июн[а-яё]*|июл[а-яё]*|август[а-яё]*|сентябр[а-яё]*|октябр[а-яё]*|ноябр[а-яё]*|декабр[а-яё]*)(?:[[:space:]]+[12][0-9]{3})?|[12][0-9]{3}))+|по[[:space:]]+желанию)$';
